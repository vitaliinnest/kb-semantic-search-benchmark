def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    prs = Presentation(str(PPTX))
    for slide_num, new_body in TRIMMED.items():
        slide = prs.slides[slide_num - 1]
        tf = slide.notes_slide.notes_text_frame
        old_text = tf.text
        # Preserve the first ⏱ line (will be regenerated anyway)
        old_lines = old_text.splitlines()
        timing_line = next((ln for ln in old_lines if ln.startswith("⏱")), "")

        tf.clear()
        if timing_line:
            tf.paragraphs[0].text = timing_line
            empty_p = tf.add_paragraph()
            empty_p.text = ""
            first_body = True
        else:
            first_body = True

        for ln in new_body.splitlines():
            if first_body and not timing_line:
                tf.paragraphs[0].text = ln
                first_body = False
            else:
                p = tf.add_paragraph()
                p.text = ln
                first_body = False

        new_words = len(new_body.split())
        print(f"Slide {slide_num:2}: {new_words} words (target ~60-85)")

    prs.save(str(PPTX))
    print(f"\nSaved: {PPTX}")
    print("Next: re-run add_slide_time_intervals.py to refresh ⏱ intervals")


if __name__ == "__main__":
    main()
