def next_backup(path: pathlib.Path) -> pathlib.Path:
    BACKUPS.mkdir(parents=True, exist_ok=True)
    for n in range(1, 100):
        p = BACKUPS / f"{path.stem}.bak{n}.pptx"
        if not p.exists():
            return p
    raise RuntimeError("too many backups")


def set_notes(slide, text: str) -> None:
    """Replace the notes-slide text. Preserves first run's formatting."""
    ns = slide.notes_slide
    tf = ns.notes_text_frame
    # Clear all paragraphs by leaving the first one and clearing its text
    if tf.paragraphs:
        # remove paragraphs beyond the first
        first = tf.paragraphs[0]
        # clear runs in first paragraph
        for r in list(first.runs):
            r._r.getparent().remove(r._r)
        # remove extra paragraphs
        for extra in list(tf.paragraphs[1:]):
            extra._p.getparent().remove(extra._p)
        # Write multi-paragraph text
        lines = text.split("\n\n")
        first.add_run().text = lines[0]
        for line in lines[1:]:
            p = tf.add_paragraph()
            p.add_run().text = line
    else:
        tf.text = text


def main() -> None:
    if not PPTX.exists():
        sys.exit(f"FAIL: pptx not found: {PPTX}")
    backup = next_backup(PPTX)
    shutil.copy2(PPTX, backup)
    print(f"[backup] {backup.name}")

    pres = Presentation(str(PPTX))
    total = len(pres.slides)
    print(f"[load] {total} slides")

    for i, slide in enumerate(pres.slides, start=1):
        if i not in NOTES:
            continue
        timing, text = NOTES[i]
        # Prepend a visible timing header so the student sees the time budget
        # in PowerPoint's notes pane while reading the script.
        annotated = f"⏱ {timing}  ·  слайд {i}/18\n\n{text}"
        set_notes(slide, annotated)
        word_count = len(text.split())
        print(f"  [{i:2d}] target {timing} · {word_count} words")

    pres.save(str(PPTX))
    print(f"[saved] {PPTX} ({PPTX.stat().st_size:,} bytes)")
    print("\nDone.")


if __name__ == "__main__":
    main()
